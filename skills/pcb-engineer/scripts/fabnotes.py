"""Write the documents that go with a fab order: stack-up + impedance notes, order notes, panel plan.

    python3 fabnotes.py hw/pcb/board.json [--board main]

Writes <out>/fab/<board>/stackup.md, order.md and, for panel mode "kikit", panel.json (KiKit preset) plus the
exact command. Called by export.py (fab) and build.py. Pure Python 3.9+.

Impedance: for a netclass with "impedance": {"ohms": 50, "layer": "F.Cu"}, the width is estimated with the
IPC-2141 microstrip formula over the first dielectric. It is an estimate: the order notes ask the fab for
controlled impedance on their own stack-up, and the fab's calculator gives the final width.
"""
import argparse
import json
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import outline as outl  # noqa: E402
import spec as specmod  # noqa: E402


def microstrip_width(z0, h, er, t=0.035):
    """IPC-2141: Z0 = 87/sqrt(er+1.41) * ln(5.98 h / (0.8 w + t)). Valid for 0.1 < w/h < 2."""
    w = (5.98 * h / math.exp(z0 * math.sqrt(er + 1.41) / 87.0) - t) / 0.8
    return w, (0.1 < w / h < 2.0) if h else False


def panel_plan(b, fab, poly):
    x0, y0, x1, y1 = outl.bbox(poly)
    w, h = x1 - x0, y1 - y0
    pm = dict(b.get("panel", {"mode": "none"}))
    need = w < fab["min_assembly"][0] or h < fab["min_assembly"][1]
    if pm.get("mode", "none") == "none" and need:
        return {"needed": True, "mode": "none", "board": [w, h]}
    if pm.get("mode", "none") == "none":
        return {"needed": False, "mode": "none", "board": [w, h]}
    sp, rail = pm.get("spacing", 2.0), pm.get("rails", 5.0)
    nx, ny = pm.get("array", [3, 3])
    sides = pm.get("rail_sides", "all")          # all (frame), tb (top/bottom rails) or lr (left/right rails)
    pw = nx * w + (nx - 1) * sp + (2 * rail if sides in ("all", "lr") else 0)
    ph = ny * h + (ny - 1) * sp + (2 * rail if sides in ("all", "tb") else 0)
    return {"needed": need, "mode": pm["mode"], "board": [round(w, 2), round(h, 2)], "array": [nx, ny],
            "spacing": sp, "rails": rail, "rail_sides": sides, "panel": [round(pw, 2), round(ph, 2)],
            "meets_min": pw >= fab["min_assembly"][0] and ph >= fab["min_assembly"][1],
            "tabs": pm.get("tabs", "mousebites"), "fiducials": pm.get("fiducials", "rails")}


def write(spec, out, bname):
    b = spec["boards"][bname]
    fab = spec["fab"]
    st = specmod.stackup(b)
    poly = outl.build(b["outline"], spec["_dir"])
    fd = os.path.join(out, "fab", bname)
    os.makedirs(fd, exist_ok=True)

    # ---- stack-up and impedance
    L = ["# %s stack-up and impedance" % bname, "",
         "Generated by fabnotes.py from %s. Order with the fab's matching stack-up; this table is the intent." %
         os.path.basename(spec["_path"]), "",
         "| Layer | Type | Thickness (mm) | Material |", "|---|---|---|---|"]
    for nm, typ, t, mat in st["stack"]:
        L.append("| %s | %s | %s | %s |" % (nm, typ, t, mat or ""))
    L += ["", "- Copper layers: %d; finished thickness %.2f mm; finish %s; mask %s." % (
        st["layers"], st["thickness"], st["finish"], st["mask_color"]), ""]
    diel = [x for x in st["stack"] if x[1] in ("core", "prepreg")]
    imp = []
    for cname, c in b["netclasses"].items():
        z = c.get("impedance")
        if not z:
            continue
        h = diel[0][2] if diel else st["thickness"]
        er = 4.5 if (diel and diel[0][3] == "FR4") else 3.3
        w, valid = microstrip_width(z["ohms"], h, er)
        imp.append((cname, z, h, er, w, valid))
    if imp:
        L += ["## Controlled impedance", "",
              "| Net class | Target | Layer / reference | Dielectric h | er | Estimated width | Note |", "|---|---|---|---|---|---|---|"]
        for cname, z, h, er, w, valid in imp:
            L.append("| %s | %s Ω %s | %s / %s | %.3f mm | %.1f | %.3f mm | [estimate: IPC-2141 microstrip]%s |" % (
                cname, z["ohms"], z.get("type", "microstrip"), z.get("layer", "F.Cu"), z.get("ref", "In1.Cu"),
                h, er, w, "" if valid else " outside the formula's range; use the fab calculator"))
        L += ["", "Ask the fab for impedance control on these nets and use the width from their calculator."]
    else:
        L += ["No controlled-impedance net classes. If the board has an RF feed or USB/high-speed pairs, add "
              "`\"impedance\": {\"ohms\": 50, \"layer\": \"F.Cu\", \"ref\": \"In1.Cu\"}` to their net class."]
    open(os.path.join(fd, "stackup.md"), "w").write("\n".join(L) + "\n")

    # ---- panel
    pp = panel_plan(b, fab, poly)
    if pp["mode"] == "kikit":
        preset = {"layout": {"type": "grid", "rows": pp["array"][1], "cols": pp["array"][0],
                             "hspace": "%gmm" % pp["spacing"], "vspace": "%gmm" % pp["spacing"]},
                  "tabs": {"type": "fixed", "width": "2mm", "vcount": 2, "hcount": 2},
                  "cuts": {"type": "mousebites", "drill": "0.5mm", "spacing": "0.8mm", "offset": "0.2mm"},
                  "framing": {"type": {"all": "frame", "tb": "railstb", "lr": "railslr"}[pp["rail_sides"]],
                              "width": "%gmm" % pp["rails"]},
                  "fiducials": {"type": "3fid", "hoffset": "2.5mm", "voffset": "2.5mm",
                                "coppersize": "1mm", "opening": "2mm"},
                  "tooling": {"type": "3hole", "hoffset": "2.5mm", "voffset": "2.5mm", "size": "1.152mm"}}
        json.dump(preset, open(os.path.join(fd, "panel.json"), "w"), indent=1)
        pp["command"] = ("kikit panelize -p %s %s %s" % (os.path.join(fd, "panel.json"),
                         os.path.join(out, bname, bname + ".kicad_pcb"), os.path.join(fd, "panel", bname + "_panel.kicad_pcb")))
    json.dump(pp, open(os.path.join(fd, "panel-plan.json"), "w"), indent=1)

    # ---- order notes
    r = b["rules"]
    sides = sorted({p["side"] for p in b["parts"] if not p["dnp"] and p.get("in_bom", True)})
    consigned = [p["ref"] for p in b["parts"] if p.get("consign") and not p["dnp"]]
    rpath = os.path.join(out, "resolved.json")
    resolved = json.load(open(rpath)).get(bname, {}) if os.path.exists(rpath) else {}
    hidden = [p["ref"] for p in b["parts"] if not p["dnp"] and any(
        k in (resolved.get(p["ref"], {}).get("footprint", "") or p.get("footprint", "")).upper()
        for k in ("QFN", "BGA", "LGA", "DFN", "WSON", "CSP", "SON-", "MLF"))]
    O = ["# Order notes: %s (rev %s)" % (bname, b["rev"]), "",
         "| Item | Value |", "|---|---|",
         "| Fab / service | %s, %s assembly |" % (fab["name"], fab["assembly"]),
         "| Quantity | %s |" % fab["quantity"],
         "| Layers / thickness | %d / %.2f mm |" % (st["layers"], st["thickness"]),
         "| Material | %s |" % ("Polyimide flex" if st["flex"] else "FR4 TG150+"),
         "| Surface finish | %s |" % st["finish"],
         "| Solder mask / silkscreen | %s / white |" % st["mask_color"],
         "| Min track / space | %.3f / %.3f mm |" % (r["min_track_width"], r["min_clearance"]),
         "| Min via | %.2f mm drill, %.2f mm pad |" % (r["min_through_hole_diameter"], r["min_via_diameter"]),
         "| Board size | %.2f × %.2f mm |" % tuple(pp["board"]),
         "| Assembly sides | %s |" % ", ".join("top" if s == "F" else "bottom" for s in sides),
         "| Impedance control | %s |" % ("yes, see stackup.md" if imp else "no"), ""]
    if pp["mode"] == "fab":
        O += ["**Panel by the fab:** %d × %d array, %.1f mm spacing, %.1f mm rails (%s), %s, "
              "3 fiducials and 3 tooling holes on the rails. Panel size %.1f × %.1f mm (%s the %g × %g mm minimum)." % (
                  pp["array"][0], pp["array"][1], pp["spacing"], pp["rails"],
                  {"all": "frame on all sides", "tb": "top and bottom", "lr": "left and right"}[pp["rail_sides"]],
                  pp["tabs"], pp["panel"][0], pp["panel"][1],
                  "meets" if pp["meets_min"] else "BELOW", fab["min_assembly"][0], fab["min_assembly"][1]), ""]
    elif pp["mode"] == "kikit":
        O += ["**Panel with KiKit** (`panel.json` in this folder): `%s`, then plot Gerbers of the panel." % pp["command"], ""]
    elif pp["needed"]:
        O += ["**PANEL MISSING:** the board is smaller than the %g × %g mm assembly minimum. Set `panel` in the spec." % tuple(fab["min_assembly"]), ""]
    if hidden:
        O += ["X-ray inspection: required for %s (hidden joints)." % ", ".join(hidden), ""]
    if consigned:
        O += ["Consigned parts (ship to the assembler, no assembler part number): %s." % ", ".join(consigned), ""]
    O += ["Check every polarized part's rotation in the assembler's placement preview before paying."]
    open(os.path.join(fd, "order.md"), "w").write("\n".join(O) + "\n")
    return {"stackup": os.path.join(fd, "stackup.md"), "order": os.path.join(fd, "order.md"), "panel": pp}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("spec")
    ap.add_argument("--board", action="append")
    ap.add_argument("--out")
    a = ap.parse_args()
    s = specmod.load(a.spec)
    out = os.path.abspath(a.out or s["_dir"])
    for bn in a.board or s["boards"]:
        r = write(s, out, bn)
        print("fabnotes: %s: %s, %s, panel %s" % (bn, r["stackup"], r["order"], r["panel"]["mode"]))


if __name__ == "__main__":
    main()
